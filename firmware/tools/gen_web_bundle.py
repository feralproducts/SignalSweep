"""Compile the built app (app/dist) into firmware/src/web_bundle.gen.cpp.

The Wi-Fi link (wifi_link.cpp) serves the app straight out of flash, so a
phone on the board's hotspot gets the whole app with no internet and no
filesystem image to flash. Each file is gzipped when that makes it smaller.

Runs two ways:
  * as a PlatformIO pre: extra_script (the c5 env), before every build;
  * by hand:  python firmware/tools/gen_web_bundle.py [app/dist]

With no app/dist present it writes a one-page placeholder, so a firmware-only
build (flash.py without building the app first) still compiles and the
hotspot says plainly what is missing. CI builds the app before the firmware.
"""
import gzip
import hashlib
import mimetypes
import os
import sys
from pathlib import Path


TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript",
    ".mjs": "application/javascript",
    ".css": "text/css",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".json": "application/json",
    ".txt": "text/plain; charset=utf-8",
    ".woff2": "font/woff2",
    ".webmanifest": "application/manifest+json",
}
# Never needed by a phone on the hotspot (Android-only splash art etc. live
# outside dist anyway); keep the flash cost honest.
SKIP_SUFFIXES = {".map"}

PLACEHOLDER = b"""<!doctype html><meta charset=utf-8><meta name=viewport content='width=device-width'>
<title>SignalSweep</title><body style='font:16px system-ui;background:#0a0e16;color:#e6edf3;padding:20px'>
<h1>SignalSweep</h1><p>This firmware was built without the app bundled in, so there is
nothing to show over Wi-Fi yet.</p><p>Build the app first (<code>cd app && npm ci && npm run build</code>),
then rebuild the firmware. The web flasher's firmware always includes it.</p></body>"""


def collect(dist: Path):
    files = []
    if not dist.is_dir() or not (dist / "index.html").is_file():
        return [("/index.html", "text/html; charset=utf-8", PLACEHOLDER)]
    for p in sorted(dist.rglob("*")):
        if not p.is_file() or p.suffix in SKIP_SUFFIXES:
            continue
        rel = "/" + p.relative_to(dist).as_posix()
        ctype = TYPES.get(p.suffix.lower()) or mimetypes.guess_type(p.name)[0] or "application/octet-stream"
        files.append((rel, ctype, p.read_bytes()))
    return files


def render(files) -> str:
    lines = [
        "// GENERATED by firmware/tools/gen_web_bundle.py -- do not edit, do not commit.",
        "#ifdef SIGNALSWEEP_WIFI_LINK",
        '#include "web_bundle.h"',
        "",
    ]
    table = []
    total = 0
    for i, (path, ctype, raw) in enumerate(files):
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        use_gz = len(gz) < len(raw) * 0.95
        data = gz if use_gz else raw
        total += len(data)
        lines.append(f"static const uint8_t A{i}[] = {{")
        for off in range(0, len(data), 32):
            lines.append("  " + ",".join(str(b) for b in data[off:off + 32]) + ",")
        lines.append("};")
        table.append(f'  {{ "{path}", "{ctype}", A{i}, {len(data)}u, {"true" if use_gz else "false"} }},')
    lines.append("")
    lines.append("const WebAsset WEB_ASSETS[] = {")
    lines.extend(table)
    lines.append("};")
    lines.append(f"const size_t WEB_ASSET_COUNT = {len(files)};")
    lines.append("#endif // SIGNALSWEEP_WIFI_LINK")
    lines.append("")
    return "\n".join(lines), total


def generate(firmware: Path, dist: Path):
    out = firmware / "src" / "web_bundle.gen.cpp"
    files = collect(dist)
    src, total = render(files)
    # Only rewrite on change, so an unchanged app doesn't force a recompile.
    old = out.read_text() if out.exists() else ""
    if hashlib.sha256(old.encode()).digest() != hashlib.sha256(src.encode()).digest():
        out.write_text(src)
    placeholder = len(files) == 1 and files[0][2] is PLACEHOLDER
    print(f"[web bundle] {'PLACEHOLDER (no app/dist)' if placeholder else f'{len(files)} files'}, "
          f"{total / 1024:.0f} KB in flash -> {out}")


if "Import" in globals():
    # PlatformIO pre: extra_script (SCons). __file__ is not defined here, so
    # the paths come from the project dir (firmware/).
    Import("env")  # noqa: F821  (provided by PlatformIO)
    _fw = Path(env["PROJECT_DIR"])  # noqa: F821
    generate(_fw, _fw.parent / "app" / "dist")
elif __name__ == "__main__":
    _fw = Path(__file__).resolve().parent.parent
    generate(_fw, Path(sys.argv[1]) if len(sys.argv) > 1 else _fw.parent / "app" / "dist")
